package ai.motionwall.cars;

import android.content.Context;
import android.content.SharedPreferences;
import android.media.MediaMetadataRetriever;
import android.net.Uri;
import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InputStream;

/**
 * Free local MP4 library. Keeps the previous selected movie intact until a
 * complete replacement is validated and fsynced. No Gallery permission,
 * server, external media account, paid API or remote generation required.
 */
public final class VideoClipStore {
    public static final String VIDEO_KEY = "video_filename";
    private static final long MAX_BYTES = 50L * 1024 * 1024;
    private VideoClipStore() {}

    public static void importVideo(Context context, Uri uri) throws IOException {
        if(uri==null)throw new IOException("Видео не выбрано");
        InputStream stream=context.getContentResolver().openInputStream(uri);
        if(stream==null)throw new IOException("Не удалось открыть MP4");
        try(InputStream in=stream) { importStream(context,in); }
    }

    /** Our original stylized animation, generated by demo/generate_demo.py. */
    public static void installFreeDemo(Context context) throws IOException {
        try(InputStream stream=context.getAssets().open("drive_demo.mp4")) {
            importStream(context,stream);
        }catch(IOException error){
            // Don't lose a previously selected video on unavailable demo assets.
            throw new IOException("Бесплатный пример недоступен: "+error.getMessage(),error);
        }
    }

    private static void importStream(Context context, InputStream in) throws IOException {
        File next=new File(context.getFilesDir(),"clip_"+System.nanoTime()+".mp4");
        try {
            long size=0;
            try(FileOutputStream out=new FileOutputStream(next)) {
                byte[] bytes=new byte[32768];int n;
                while((n=in.read(bytes))!=-1){
                    size+=n;
                    if(size>MAX_BYTES)throw new IOException("MP4 слишком большой: максимум 50 МБ");
                    out.write(bytes,0,n);
                }
                out.getFD().sync();
            }
            if(size<4096)throw new IOException("Пустой или повреждённый MP4");
            validateClip(next);
            SharedPreferences preferences=context.getSharedPreferences(PhotoStore.PREFS,Context.MODE_PRIVATE);
            String previous=preferences.getString(VIDEO_KEY,null);
            if(!preferences.edit().putString(VIDEO_KEY,next.getName()).commit())
                throw new IOException("Не удалось сохранить MP4 в проект");
            if(previous!=null&&previous.matches("clip_[0-9]+\\.mp4"))
                new File(context.getFilesDir(),previous).delete();
        }catch(Exception error){
            next.delete();
            if(error instanceof IOException)throw (IOException)error;
            throw new IOException("Не удалось проверить видео: "+error.getMessage(),error);
        }
    }

    private static void validateClip(File file) throws IOException {
        MediaMetadataRetriever metadata=new MediaMetadataRetriever();
        try {
            metadata.setDataSource(file.getAbsolutePath());
            int width=parseInt(metadata.extractMetadata(MediaMetadataRetriever.METADATA_KEY_VIDEO_WIDTH));
            int height=parseInt(metadata.extractMetadata(MediaMetadataRetriever.METADATA_KEY_VIDEO_HEIGHT));
            long milliseconds=parseLong(metadata.extractMetadata(MediaMetadataRetriever.METADATA_KEY_DURATION));
            if(width<64||height<64||milliseconds<1000||milliseconds>30000)
                throw new IOException("Нужно настоящее видео длительностью 1–30 секунд");
            if((long)width*height > 3840L*2160L)
                throw new IOException("4K максимум. Для живых обоев лучше 720p");
        }finally{metadata.release();}
    }
    private static int parseInt(String value){
        try{return Integer.parseInt(value);}catch(Exception e){return 0;}
    }
    private static long parseLong(String value){
        try{return Long.parseLong(value);}catch(Exception e){return 0;}
    }
    public static File get(Context context) {
        String name=context.getSharedPreferences(PhotoStore.PREFS,Context.MODE_PRIVATE)
            .getString(VIDEO_KEY,null);
        if(name==null||!name.matches("clip_[0-9]+\\.mp4"))return null;
        File f=new File(context.getFilesDir(),name);
        return f.isFile()&&f.length()>0?f:null;
    }
}
